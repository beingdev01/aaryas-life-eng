#!/usr/bin/env python3
"""term_tracker: keep Lakshya's academic calendar in one JSON file you pass by path.

Two programmes: IITM (IIT Madras BS in Data Science) and CCSU (BTech IT at SCRIET,
CCSU Meerut). Every entry records where the date came from and whether it is confirmed.

Calendar file:
  {"schema": "aaryas-life/academics-calendar/v1", "entries": [ENTRY, ...]}
ENTRY fields:
  id         unique; generated by `add` when not given
  course     course name or code, e.g. "MLP" or "Data Mining"
  programme  IITM | CCSU
  kind       deadline | exam | quiz | class | other
  title      optional, e.g. "Week 6 graded assignment"
  date       YYYY-MM-DD
  time       HH:MM (24 h), or null only when status is tentative
  timezone   IST (default), Asia/Kolkata, UTC, or another IANA zone name
  source     where the date came from: URL, notice title and date, or who said it
  status     confirmed | tentative
  notes      optional

All output is in IST. An entry with no time is treated as 23:59 IST on its date.

Subcommands:
  add        append one entry (creates the file if it does not exist)
  update     change an entry's date, time, timezone, status or title; a new --source is
             required and the previous values are kept in notes
  list       every entry, sorted, with optional filters
  upcoming   entries in the next N days
  remind     entries whose reminder fires on a day (exam/quiz 14,7,3,1; deadline 7,3,1;
             class/other 1 day ahead; plus the day itself)
  clashes    exams, quizzes and deadlines of the two programmes on the same IST day
             (or within --window days)
  validate   check the whole file; exit 1 with the reasons if malformed

Exit codes: 0 ok, 1 malformed calendar or failed check, 2 usage error.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import sys
import tempfile
from pathlib import Path

try:
    from zoneinfo import ZoneInfo, ZoneInfoNotFoundError
except ImportError:  # pragma: no cover - Python < 3.9
    ZoneInfo = None
    ZoneInfoNotFoundError = Exception

SCHEMA = "aaryas-life/academics-calendar/v1"
PROGRAMMES = ("IITM", "CCSU")
KINDS = ("deadline", "exam", "quiz", "class", "other")
STATUSES = ("confirmed", "tentative")
FIELDS = {"id", "course", "programme", "kind", "title", "date", "time", "timezone",
          "source", "status", "notes"}
REQUIRED = ("course", "programme", "kind", "date", "timezone", "source", "status")
VAGUE_SOURCES = {"", "unknown", "none", "n/a", "na", "-", "?", "tbd", "todo"}
EXAM_LIKE = ("exam", "quiz")
LEAD_DAYS = {"exam": (14, 7, 3, 1, 0), "quiz": (14, 7, 3, 1, 0),
             "deadline": (7, 3, 1, 0), "class": (1, 0), "other": (1, 0)}
IST = dt.timezone(dt.timedelta(hours=5, minutes=30), "IST")


class CalendarError(ValueError):
    pass


def zone(name: str):
    if name in ("IST", "Asia/Kolkata", "Asia/Calcutta"):
        return IST
    if name in ("UTC", "Etc/UTC", "GMT"):
        return dt.timezone.utc
    if ZoneInfo is None:
        raise CalendarError(f"unknown timezone '{name}'")
    try:
        return ZoneInfo(name)
    except (ZoneInfoNotFoundError, ValueError, KeyError):
        raise CalendarError(f"unknown timezone '{name}' (use IST or an IANA name)")


def entry_problems(e, index: int) -> list[str]:
    label = f"entry {index + 1}"
    if not isinstance(e, dict):
        return [f"{label}: must be an object"]
    if e.get("id"):
        label += f" ({e['id']})"
    out = []
    unknown = sorted(set(e) - FIELDS)
    if unknown:
        out.append(f"{label}: unknown field(s) {', '.join(unknown)}")
    for key in REQUIRED:
        if key not in e or e[key] is None or (isinstance(e[key], str) and not e[key].strip()):
            out.append(f"{label}: missing '{key}'")
    for key in ("id", "course", "title", "source", "notes", "timezone", "date"):
        if key in e and e[key] is not None and not isinstance(e[key], str):
            out.append(f"{label}: '{key}' must be a string")
    if out:
        return out
    if e["programme"] not in PROGRAMMES:
        out.append(f"{label}: programme '{e['programme']}' must be IITM or CCSU")
    if e["kind"] not in KINDS:
        out.append(f"{label}: kind '{e['kind']}' must be one of {', '.join(KINDS)}")
    if e["status"] not in STATUSES:
        out.append(f"{label}: status '{e['status']}' must be confirmed or tentative")
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", e["date"]):
        out.append(f"{label}: bad date '{e['date']}' (want YYYY-MM-DD)")
    else:
        try:
            dt.date.fromisoformat(e["date"])
        except ValueError:
            out.append(f"{label}: '{e['date']}' is not a real date")
    t = e.get("time")
    if t is None or t == "":
        if e["status"] == "confirmed":
            out.append(f"{label}: a confirmed entry needs a time (HH:MM); mark it "
                       f"tentative if the time is not known")
    elif not isinstance(t, str) or not re.fullmatch(r"([01]\d|2[0-3]):[0-5]\d", t):
        out.append(f"{label}: bad time '{t}' (want HH:MM, 24 hour)")
    try:
        zone(e["timezone"])
    except CalendarError as exc:
        out.append(f"{label}: {exc}")
    if e["source"].strip().lower() in VAGUE_SOURCES:
        out.append(f"{label}: source '{e['source']}' does not say where the date came from")
    return out


def calendar_problems(data) -> list[str]:
    if not isinstance(data, dict):
        return ["calendar must be a JSON object with an 'entries' list"]
    if "schema" in data and data["schema"] != SCHEMA:
        return [f"unknown schema '{data['schema']}' (want {SCHEMA})"]
    entries = data.get("entries")
    if not isinstance(entries, list):
        return ["calendar has no 'entries' list"]
    out = []
    seen: dict[str, int] = {}
    for i, e in enumerate(entries):
        out.extend(entry_problems(e, i))
        if isinstance(e, dict) and e.get("id"):
            if e["id"] in seen:
                out.append(f"entry {i + 1}: duplicate id '{e['id']}' (also entry "
                           f"{seen[e['id']] + 1})")
            seen.setdefault(e["id"], i)
    return out


def read_calendar(path: Path, missing_ok: bool = False) -> dict:
    if not path.exists():
        if missing_ok:
            return {"schema": SCHEMA, "entries": []}
        raise CalendarError(f"{path}: no such calendar file")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise CalendarError(f"{path}: not valid JSON (line {exc.lineno}: {exc.msg})")
    except OSError as exc:
        raise CalendarError(f"{path}: cannot read ({exc.strerror or exc})")
    probs = calendar_problems(data)
    if probs:
        more = f" (+{len(probs) - 1} more; run validate)" if len(probs) > 1 else ""
        raise CalendarError(f"{path}: {probs[0]}{more}")
    return data


def write_calendar(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".term_tracker.", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump(data, fh, indent=2, ensure_ascii=False)
            fh.write("\n")
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def when_ist(e: dict) -> dt.datetime:
    d = dt.date.fromisoformat(e["date"])
    t = e.get("time") or "23:59"
    hh, mm = (int(x) for x in t.split(":"))
    local = dt.datetime(d.year, d.month, d.day, hh, mm, tzinfo=zone(e["timezone"]))
    return local.astimezone(IST)


def sorted_entries(data: dict) -> list[dict]:
    return sorted(data["entries"], key=lambda e: (when_ist(e), e["programme"], e["course"]))


def today_ist() -> dt.date:
    return dt.datetime.now(IST).date()


def parse_day(text: str | None) -> dt.date:
    if not text:
        return today_ist()
    try:
        return dt.date.fromisoformat(text)
    except ValueError:
        raise CalendarError(f"bad --from date '{text}' (want YYYY-MM-DD)")


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "x"


def fmt(e: dict, ref: dt.date | None = None) -> str:
    w = when_ist(e)
    time = f"{w:%H:%M} IST" if e.get("time") else "time ? IST"
    title = f"  {e['title']}" if e.get("title") else ""
    rel = ""
    if ref is not None:
        days = (w.date() - ref).days
        rel = "  today" if days == 0 else f"  in {days} day{'s' if days != 1 else ''}"
    return (f"{w:%Y-%m-%d %a} {time:<10} {e['programme']:<4} {e['kind']:<8} "
            f"{e['course']}{title}  [{e['status']}]{rel}  (source: {e['source']})")


def emit(rows: list[dict], as_json: bool, ref=None, empty="no entries") -> None:
    if as_json:
        out = []
        for e in rows:
            item = dict(e)
            item["when_ist"] = when_ist(e).isoformat()
            if ref is not None:
                item["days_left"] = (when_ist(e).date() - ref).days
            out.append(item)
        print(json.dumps(out, indent=2, ensure_ascii=False))
        return
    if not rows:
        print(empty)
    for e in rows:
        print(fmt(e, ref))


def filtered(rows, args):
    if getattr(args, "programme", None):
        rows = [e for e in rows if e["programme"] == args.programme]
    if getattr(args, "kind", None):
        rows = [e for e in rows if e["kind"] == args.kind]
    if getattr(args, "status", None):
        rows = [e for e in rows if e["status"] == args.status]
    return rows


def cmd_add(args) -> int:
    path = Path(args.calendar)
    data = read_calendar(path, missing_ok=True)
    entry = {"course": args.course.strip(), "programme": args.programme,
             "kind": args.kind, "date": args.date, "time": args.time or None,
             "timezone": args.timezone, "source": args.source.strip(),
             "status": args.status}
    if args.title:
        entry["title"] = args.title.strip()
    if args.notes:
        entry["notes"] = args.notes.strip()
    probs = entry_problems(entry, len(data["entries"]))
    if probs:
        raise CalendarError(probs[0])
    for other in data["entries"]:
        same = all(other.get(k) == entry.get(k) for k in ("programme", "kind", "date"))
        if same and other["course"].lower() == entry["course"].lower() and \
                (other.get("title") or "").lower() == (entry.get("title") or "").lower():
            raise CalendarError(f"duplicate of existing entry '{other.get('id')}'")
    ids = {e.get("id") for e in data["entries"]}
    base = args.id or f"{entry['programme'].lower()}-{slug(entry['course'])}-{entry['kind']}-{entry['date']}"
    if args.id and base in ids:
        raise CalendarError(f"id '{base}' already exists")
    new_id, n = base, 2
    while new_id in ids:
        new_id, n = f"{base}-{n}", n + 1
    entry = {"id": new_id, **entry}
    data["entries"].append(entry)
    data.setdefault("schema", SCHEMA)
    write_calendar(path, data)
    print(f"added {new_id}: {fmt(entry)}")
    return 0


def cmd_update(args) -> int:
    path = Path(args.calendar)
    data = read_calendar(path)
    match = [e for e in data["entries"] if e.get("id") == args.id]
    if not match:
        raise CalendarError(f"no entry with id '{args.id}'")
    entry = match[0]
    changes = {k: v for k, v in (("date", args.date), ("time", args.time),
                                 ("timezone", args.timezone), ("status", args.status),
                                 ("title", args.title)) if v is not None}
    if args.no_time:
        changes["time"] = None
    if not changes:
        raise CalendarError("nothing to change; pass --date, --time, --no-time, "
                            "--timezone, --status or --title")
    before = {k: entry.get(k) for k in ("date", "time", "timezone", "status", "source")}
    updated = dict(entry, **changes, source=args.source.strip())
    was = (f"was {before['date']} {before['time'] or 'no time'} {before['timezone']} "
           f"{before['status']} (source: {before['source']})")
    updated["notes"] = f"{entry['notes']}; {was}" if entry.get("notes") else was
    probs = entry_problems(updated, data["entries"].index(entry))
    if probs:
        raise CalendarError(probs[0])
    data["entries"][data["entries"].index(entry)] = updated
    write_calendar(path, data)
    print(f"updated {args.id}: {fmt(updated)}")
    return 0


def cmd_list(args) -> int:
    data = read_calendar(Path(args.calendar))
    emit(filtered(sorted_entries(data), args), args.json, empty="calendar has no entries")
    return 0


def window(data, start: dt.date, days: int) -> list[dict]:
    end = start + dt.timedelta(days=days)
    return [e for e in sorted_entries(data) if start <= when_ist(e).date() < end]


def cmd_upcoming(args) -> int:
    if args.days < 1:
        raise CalendarError("--days must be at least 1")
    data = read_calendar(Path(args.calendar))
    start = parse_day(args.from_)
    rows = filtered(window(data, start, args.days), args)
    emit(rows, args.json, ref=start,
         empty=f"no entries in the {args.days} day(s) from {start.isoformat()}")
    return 0


def cmd_remind(args) -> int:
    data = read_calendar(Path(args.calendar))
    day = parse_day(args.from_)
    rows = []
    for e in sorted_entries(data):
        left = (when_ist(e).date() - day).days
        if left in LEAD_DAYS[e["kind"]]:
            rows.append(e)
    rows = filtered(rows, args)
    emit(rows, args.json, ref=day, empty=f"no reminders fire on {day.isoformat()}")
    return 0


def find_clashes(data, start: dt.date | None, days: int | None, window_days: int,
                 kinds) -> list[tuple[dict, dict, int]]:
    rows = [e for e in sorted_entries(data) if e["kind"] in kinds]
    if start is not None:
        rows = [e for e in rows if when_ist(e).date() >= start]
        if days is not None:
            end = start + dt.timedelta(days=days)
            rows = [e for e in rows if when_ist(e).date() < end]
    out = []
    iitm = [e for e in rows if e["programme"] == "IITM"]
    ccsu = [e for e in rows if e["programme"] == "CCSU"]
    for a in iitm:
        for b in ccsu:
            gap = abs((when_ist(a).date() - when_ist(b).date()).days)
            if gap <= window_days:
                out.append((a, b, gap))
    out.sort(key=lambda t: (min(when_ist(t[0]), when_ist(t[1])), t[2]))
    return out


def cmd_clashes(args) -> int:
    data = read_calendar(Path(args.calendar))
    kinds = [k.strip() for k in args.kinds.split(",") if k.strip()]
    bad = [k for k in kinds if k not in KINDS]
    if bad:
        raise CalendarError(f"unknown kind(s) in --kinds: {', '.join(bad)}")
    if args.window < 0:
        raise CalendarError("--window must be 0 or more")
    start = parse_day(args.from_) if (args.from_ or args.days) else None
    clashes = find_clashes(data, start, args.days, args.window, kinds)
    if args.json:
        print(json.dumps([{"iitm": a, "ccsu": b, "days_apart": gap}
                          for a, b, gap in clashes], indent=2, ensure_ascii=False))
    elif not clashes:
        span = "same day" if args.window == 0 else f"within {args.window} day(s)"
        print(f"no clashes ({span}, kinds: {', '.join(kinds)})")
    else:
        for a, b, gap in clashes:
            what = "CLASH (same day)" if gap == 0 else f"NEAR ({gap} day(s) apart)"
            print(f"{what}\n  {fmt(a)}\n  {fmt(b)}")
        same = sum(1 for c in clashes if c[2] == 0)
        if args.window == 0:
            print(f"{len(clashes)} clash(es) on the same day")
        else:
            print(f"{len(clashes)} clash(es): {same} on the same day, {len(clashes) - same} "
                  f"within {args.window} day(s)")
    if clashes and args.strict:
        print(f"term_tracker: {len(clashes)} clash(es) between IITM and CCSU", file=sys.stderr)
        return 1
    return 0


def cmd_validate(args) -> int:
    path = Path(args.calendar)
    if not path.exists():
        raise CalendarError(f"{path}: no such calendar file")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise CalendarError(f"{path}: not valid JSON (line {exc.lineno}: {exc.msg})")
    probs = calendar_problems(data)
    if probs:
        for p in probs:
            print(f"{path}: {p}")
        raise CalendarError(f"{path}: {len(probs)} problem(s); first: {probs[0]}")
    entries = data["entries"]
    conf = sum(1 for e in entries if e["status"] == "confirmed")
    by = {p: sum(1 for e in entries if e["programme"] == p) for p in PROGRAMMES}
    print(f"calendar OK {path}: {len(entries)} entries ({conf} confirmed, "
          f"{len(entries) - conf} tentative; IITM {by['IITM']}, CCSU {by['CCSU']})")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="term_tracker.py",
        description="Academic calendar for the IITM BS and CCSU BTech programmes: add, "
                    "update, list, upcoming, remind, clashes, validate. Times shown in IST.",
        epilog="Example: term_tracker.py upcoming --calendar calendar.json --days 14")
    sub = parser.add_subparsers(dest="cmd", required=True)

    def common(p, filters=True):
        p.add_argument("--calendar", required=True, help="path to the calendar JSON file")
        if filters:
            p.add_argument("--programme", choices=PROGRAMMES)
            p.add_argument("--kind", choices=KINDS)
            p.add_argument("--status", choices=STATUSES)
            p.add_argument("--json", action="store_true", help="print JSON")

    p = sub.add_parser("add", help="append one entry")
    common(p, filters=False)
    p.add_argument("--course", required=True)
    p.add_argument("--programme", required=True, choices=PROGRAMMES)
    p.add_argument("--kind", required=True, choices=KINDS)
    p.add_argument("--date", required=True, help="YYYY-MM-DD")
    p.add_argument("--time", default=None, help="HH:MM 24 hour; omit only if tentative")
    p.add_argument("--timezone", default="IST")
    p.add_argument("--source", required=True, help="URL, notice title and date, or who said it")
    p.add_argument("--status", required=True, choices=STATUSES)
    p.add_argument("--title", default=None)
    p.add_argument("--notes", default=None)
    p.add_argument("--id", default=None)
    p.set_defaults(func=cmd_add)

    p = sub.add_parser("update", help="change one entry; needs a new --source")
    p.add_argument("--calendar", required=True, help="path to the calendar JSON file")
    p.add_argument("--id", required=True)
    p.add_argument("--source", required=True, help="the source of the new information")
    p.add_argument("--date", default=None)
    p.add_argument("--time", default=None)
    p.add_argument("--no-time", action="store_true", help="clear the time (tentative only)")
    p.add_argument("--timezone", default=None)
    p.add_argument("--status", default=None, choices=STATUSES)
    p.add_argument("--title", default=None)
    p.set_defaults(func=cmd_update)

    p = sub.add_parser("list", help="every entry, sorted by IST time")
    common(p)
    p.set_defaults(func=cmd_list)

    p = sub.add_parser("upcoming", help="entries in the next N days")
    common(p)
    p.add_argument("--days", type=int, default=14)
    p.add_argument("--from", dest="from_", default=None, help="start day YYYY-MM-DD "
                                                                "(default: today in IST)")
    p.set_defaults(func=cmd_upcoming)

    p = sub.add_parser("remind", help="entries whose reminder fires on a day")
    common(p)
    p.add_argument("--from", dest="from_", default=None, help="the day, YYYY-MM-DD "
                                                                "(default: today in IST)")
    p.set_defaults(func=cmd_remind)

    p = sub.add_parser("clashes", help="IITM and CCSU exams/deadlines on the same day")
    p.add_argument("--calendar", required=True, help="path to the calendar JSON file")
    p.add_argument("--kinds", default="exam,quiz,deadline",
                   help="comma list of kinds to compare (default exam,quiz,deadline)")
    p.add_argument("--window", type=int, default=0,
                   help="also report items this many days apart (default 0 = same day)")
    p.add_argument("--from", dest="from_", default=None, help="ignore items before this day")
    p.add_argument("--days", type=int, default=None, help="only look this many days ahead")
    p.add_argument("--strict", action="store_true", help="exit 1 if any clash is found")
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_clashes)

    p = sub.add_parser("validate", help="check the whole calendar file")
    p.add_argument("--calendar", required=True)
    p.set_defaults(func=cmd_validate)
    return parser


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except CalendarError as exc:
        print(f"term_tracker: {exc}", file=sys.stderr)
        return 1
    except OSError as exc:
        print(f"term_tracker: {exc.strerror or exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
